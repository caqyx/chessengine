#!/usr/bin/env python3
"""Turn a network file into C source so it can be compiled into the engine.

    python3 tools/embed_net.py                      # engine/net/tessera.nnue -> engine/src/net_data.h
    python3 tools/embed_net.py nets/tessera.nnue    # use a freshly trained network instead

Run it after training a better network, then rebuild (make -C engine, make -C engine wasm).
The engine uses the embedded network by default; 'setoption name EvalFile' still overrides it.
"""
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT = os.path.join(ROOT, "engine", "net", "tessera.nnue")
OUT = os.path.join(ROOT, "engine", "src", "net_data.h")


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    data = open(src, "rb").read()
    if data[:4] != b"TSNN":
        sys.exit(f"{src} is not a Tessera network file")
    if os.path.abspath(src) != DEFAULT:
        shutil.copyfile(src, DEFAULT)           # keep the binary next to the generated source
    hidden = int.from_bytes(data[8:12], "little")
    lines = [
        "// Generated by tools/embed_net.py from engine/net/tessera.nnue. Do not edit.",
        f"// The network the engine uses by default: {hidden} hidden units, {len(data)} bytes.",
        "#pragma once",
        f"static const unsigned char DefaultNet[{len(data)}] = {{",
    ]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({hidden} hidden units, {len(data):,} bytes)")


if __name__ == "__main__":
    main()
